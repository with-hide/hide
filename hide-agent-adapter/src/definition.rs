//! Agent definition files (PRD engine-bundle-3-core-owns D-16, D-17, D-20):
//! one TOML file per agent naming how it is recognized, started and resumed,
//! which of Hide's hook dialects reads it, and the rules its state is read
//! from on the screen.
//!
//! The built-in files are `agents/*.toml` in this crate: the seven agents
//! with Hide's own features, whose identity `AgentAdapter` reads from the
//! constants `build.rs` generates out of these files, and sixteen agents
//! with screen rules taken from Herdr's manifests, which have the definition
//! only. The operator's own files (`~/.hide/agents/*.toml`, read by
//! `hide_kit::agent_definitions`) come after them in name order: a file with
//! a built-in agent's id replaces that agent's screen rules only, and a new
//! id either names its program and `hooks = "none"` or copies a built-in
//! agent with `based_on`. A file that cannot be used is left out alone, with
//! one line saying why.
//!
//! Built-in and user files go through the same reading and the same checks
//! ([`read_file`], [`Claims`]); only what each may say differs. Nothing here
//! reads a file system or the network: screen rules come from the app's own
//! files and the operator's, never from a download (D-19).

use std::collections::BTreeMap;
use std::sync::{Arc, LazyLock};

pub use hide_screen_rules::Rules;

mod file;
use file::{Fields, Origin, required};
pub use file::{
    ACCOUNT_PART, AccountRule, AccountVar, Base, By, AccountPath, Hooks, LINE_BYTES, LINE_WORDS,
    PathRule, SCHEMA, Template, is_plain_command, is_typable_word, reserved_variable,
    valid_variable,
};

/// A built-in definition's fields as constants, generated by `build.rs`
/// from `agents/<id>.toml`; `AgentAdapter` reads its identity from these.
#[derive(Debug)]
pub struct Builtin {
    pub id: &'static str,
    pub name: &'static str,
    pub executables: &'static [&'static str],
    pub aliases: &'static [&'static str],
    /// The agent's own folder under the account's home, as its parts.
    pub home: Option<&'static [&'static str]>,
    pub hooks: Hooks,
    pub start_args: &'static [&'static str],
    pub resume_session: Option<&'static [&'static str]>,
    pub resume_last: Option<&'static [&'static str]>,
    /// The file itself, for the screen rules.
    pub text: &'static str,
}

pub(crate) mod builtin {
    use super::{Builtin, Hooks};
    include!(concat!(env!("OUT_DIR"), "/builtin.rs"));
}

/// The most files read from the operator's folder; the rest are left out.
pub const MAX_USER_FILES: usize = 64;
/// The largest file read from the operator's folder.
pub const MAX_FILE_BYTES: u64 = 256 * 1024;

/// Where a definition, or its screen rules, came from.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Source {
    Builtin,
    /// A file in the operator's folder, by its name there.
    User(String),
}

#[derive(Clone, Debug)]
pub struct Screen {
    pub rules: Arc<Rules>,
    pub source: Source,
}

/// One agent as Hide knows it.
#[derive(Clone, Debug)]
pub struct Definition {
    pub id: String,
    pub name: String,
    pub executables: Vec<String>,
    /// Exact npm package identities for scripts whose file names are generic.
    pub packages: Vec<String>,
    pub aliases: Vec<String>,
    /// The agent's own folder under the account's home, as its parts.
    pub home: Option<Vec<String>>,
    pub hooks: Hooks,
    pub start_args: Vec<String>,
    /// The id of the idle screen rule that shows the program ready for a
    /// start's first input (`[start] ready`): a start waits for its screen
    /// to match it. It always names a rule of [`Self::screen`].
    pub start_ready: Option<String>,
    pub resume_session: Option<Vec<String>>,
    pub resume_last: Option<Vec<String>>,
    pub screen: Option<Screen>,
    /// Where the agent keeps an account's folders (`[account]`), read only
    /// through `crate::resolve`; `None` for an agent Hide keeps no folder of.
    pub account: Option<AccountRule>,
    pub source: Source,
    /// The built-in agent a user file copied.
    pub based_on: Option<String>,
}

/// A file of the operator's that was left out, and why, in one line that
/// starts with the file's name.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Rejected {
    pub file: String,
    pub reason: String,
}

/// A file found in the operator's folder, as the folder reader hands it in.
#[derive(Clone, Debug)]
pub enum UserFile {
    Text {
        name: String,
        text: String,
    },
    /// Larger than [`MAX_FILE_BYTES`]; not read.
    TooLarge {
        name: String,
        bytes: u64,
    },
    /// Past the first [`MAX_USER_FILES`] in name order; not read.
    BeyondLimit {
        name: String,
    },
    Unreadable {
        name: String,
        error: String,
    },
}

/// Every agent this Hide knows: the built-in ones, then the operator's, with
/// the operator's files that were left out.
#[derive(Clone, Debug)]
pub struct Catalog {
    pub definitions: Vec<Definition>,
    pub rejected: Vec<Rejected>,
}

/// The built-in definitions, read and checked once. A built-in file that
/// fails a check is a bug this crate's tests catch, never an operator's
/// problem, so it stops the process with the reason.
pub fn builtins() -> &'static [Definition] {
    static BUILTINS: LazyLock<Vec<Definition>> = LazyLock::new(|| {
        let mut claims = Claims::default();
        builtin::ALL
            .iter()
            .map(|builtin| {
                let name = format!("{}.toml", builtin.id);
                read_file(&name, builtin.text, Origin::Builtin)
                    .and_then(|file| new_definition(&name, file, Source::Builtin))
                    .and_then(|definition| claims.claim(&name, &definition).map(|()| definition))
                    .unwrap_or_else(|reason| panic!("built-in agent definition: {reason}"))
            })
            .collect()
    });
    &BUILTINS
}

/// The `[account]` of the built-in definition with this id, read once
/// without compiling any screen rules: an account's folders are asked on
/// paths that cannot wait for every agent's rules to compile.
pub fn builtin_account(id: &str) -> Option<&'static AccountRule> {
    static ACCOUNTS: LazyLock<Vec<(&'static str, Option<AccountRule>)>> = LazyLock::new(|| {
        builtin::ALL
            .iter()
            .map(|builtin| {
                let name = format!("{}.toml", builtin.id);
                let fields = file::read(&name, builtin.text, Origin::Builtin)
                    .unwrap_or_else(|reason| panic!("built-in agent definition: {reason}"));
                (builtin.id, fields.account)
            })
            .collect()
    });
    ACCOUNTS
        .iter()
        .find(|(each, _)| *each == id)
        .and_then(|(_, account)| account.as_ref())
}

/// The built-in definition with this id.
pub fn builtin(id: &str) -> Option<&'static Definition> {
    builtins().iter().find(|definition| definition.id == id)
}

/// The definition among `definitions` that `kind` names, by its id or one of
/// its aliases, ignoring case: the one rule every caller reads a kind by.
pub fn find<'a>(definitions: &'a [Definition], kind: &str) -> Option<&'a Definition> {
    let kind = kind.trim();
    definitions.iter().find(|definition| {
        definition.id.eq_ignore_ascii_case(kind)
            || definition
                .aliases
                .iter()
                .any(|alias| alias.eq_ignore_ascii_case(kind))
    })
}

impl Catalog {
    /// The built-in definitions with the operator's files read over them,
    /// in the order handed in (the folder's name order).
    pub fn read(files: Vec<UserFile>) -> Self {
        let mut definitions = builtins().to_vec();
        let mut claims = Claims::default();
        for definition in &definitions {
            claims
                .claim("", definition)
                .expect("built-in definitions claim distinct names");
        }
        let mut overridden: BTreeMap<String, String> = BTreeMap::new();
        let mut rejected = Vec::new();
        for file in files {
            let (name, text) = match file {
                UserFile::Text { name, text } => (name, text),
                UserFile::TooLarge { name, bytes } => {
                    let reason = format!(
                        "{name}: {bytes} bytes, more than the {MAX_FILE_BYTES} a file may hold"
                    );
                    rejected.push(Rejected { file: name, reason });
                    continue;
                }
                UserFile::BeyondLimit { name } => {
                    let reason =
                        format!("{name}: past the first {MAX_USER_FILES} files, which are read");
                    rejected.push(Rejected { file: name, reason });
                    continue;
                }
                UserFile::Unreadable { name, error } => {
                    let reason = format!("{name}: could not be read: {error}");
                    rejected.push(Rejected { file: name, reason });
                    continue;
                }
            };
            let result = read_file(&name, &text, Origin::User).and_then(|read| {
                let id = read.0.id.clone();
                if let Some(index) = definitions.iter().position(|definition| {
                    definition.source == Source::Builtin && definition.id == id
                }) {
                    let screen = screen_override(&name, read)?;
                    // The agent's start waits for its ready rule, so rules
                    // without it would hold every start to its deadline.
                    check_ready(
                        &name,
                        definitions[index].start_ready.as_deref(),
                        Some(&screen),
                    )?;
                    // Only a file that replaced the rules is remembered, so
                    // a later refusal names that file and not one left out.
                    if let Some(earlier) = overridden.get(&id) {
                        return Err(format!(
                            "{name}: {earlier} already replaces the screen rules of {id}"
                        ));
                    }
                    overridden.insert(id, name.clone());
                    definitions[index].screen = Some(screen);
                    return Ok(());
                }
                let definition = match read.0.based_on.clone() {
                    Some(base) => based_on(&name, read, &base)?,
                    None => new_definition(&name, read, Source::User(name.clone()))?,
                };
                claims.claim(&name, &definition)?;
                definitions.push(definition);
                Ok(())
            });
            if let Err(reason) = result {
                rejected.push(Rejected { file: name, reason });
            }
        }
        Self {
            definitions,
            rejected,
        }
    }
}

/// Read one file through the one check of its fields ([`file::read`]) and
/// compile its screen rules.
fn read_file(name: &str, text: &str, origin: Origin) -> Result<(Fields, Option<Rules>), String> {
    let mut fields = file::read(name, text, origin)?;
    let screen = fields
        .screen
        .take()
        .map(|table| {
            table
                .try_into::<hide_screen_rules::Manifest>()
                .map_err(|error| error.to_string())
                .and_then(hide_screen_rules::Manifest::compile)
                .map_err(|error| format!("{name}: screen rules: {}", first_line(&error)))
        })
        .transpose()?;
    Ok((fields, screen))
}

/// A definition of its own: a built-in file, or an operator's file for an
/// agent Hide knows only through it, which names its program and reads the
/// state from the screen alone.
fn new_definition(
    name: &str,
    (file, screen): (Fields, Option<Rules>),
    source: Source,
) -> Result<Definition, String> {
    let display = required(name, "name", file.name)?;
    let executables = required(name, "executables", file.executables)?;
    let hooks = required(name, "hooks", file.hooks)?;
    if source != Source::Builtin && hooks != Hooks::None {
        return Err(format!(
            "{name}: hooks must be \"none\"; a file takes another agent's hooks with based_on"
        ));
    }
    let screen = screen.map(|rules| Screen {
        rules: Arc::new(rules),
        source: source.clone(),
    });
    check_ready(name, file.start_ready.as_deref(), screen.as_ref())?;
    Ok(Definition {
        id: file.id,
        name: display,
        executables,
        packages: file.packages.unwrap_or_default(),
        aliases: file.aliases.unwrap_or_default(),
        home: file.home,
        hooks,
        start_args: file.start_args.unwrap_or_default(),
        start_ready: file.start_ready,
        resume_session: file.resume_session,
        resume_last: file.resume_last,
        screen,
        account: file.account,
        source,
        based_on: None,
    })
}

/// A copy of a built-in agent with what the file says in place of its
/// fields: the copy keeps the agent's hooks and everything Hide does with
/// them, and a copy of a copy is refused.
fn based_on(
    name: &str,
    (file, screen): (Fields, Option<Rules>),
    base: &str,
) -> Result<Definition, String> {
    let Some(builtin) = builtin(base) else {
        return Err(format!("{name}: based_on {base} is not a built-in agent"));
    };
    if file.hooks.is_some() {
        return Err(format!(
            "{name}: hooks comes from based_on {base} and cannot be set"
        ));
    }
    // The hooks a copy keeps are installed where the copied agent's account
    // keeps them, so the copy reads its folders by the same rule.
    if file.account.is_some() {
        return Err(format!(
            "{name}: account comes from based_on {base} and cannot be set"
        ));
    }
    let display = required(name, "name", file.name)?;
    let source = Source::User(name.to_owned());
    let screen = match screen {
        Some(rules) => Some(Screen {
            rules: Arc::new(rules),
            source: source.clone(),
        }),
        None => builtin.screen.clone(),
    };
    let start_ready = file.start_ready.or_else(|| builtin.start_ready.clone());
    check_ready(name, start_ready.as_deref(), screen.as_ref())?;
    Ok(Definition {
        id: file.id,
        name: display,
        executables: file
            .executables
            .unwrap_or_else(|| builtin.executables.clone()),
        // Like aliases, package identities belong to this definition,
        // rather than claiming the copied agent's identity a second time.
        packages: file.packages.unwrap_or_default(),
        aliases: file.aliases.unwrap_or_default(),
        home: file.home.or_else(|| builtin.home.clone()),
        hooks: builtin.hooks,
        start_args: file
            .start_args
            .unwrap_or_else(|| builtin.start_args.clone()),
        start_ready,
        resume_session: file
            .resume_session
            .or_else(|| builtin.resume_session.clone()),
        resume_last: file.resume_last.or_else(|| builtin.resume_last.clone()),
        screen,
        account: builtin.account.clone(),
        source,
        based_on: Some(base.to_owned()),
    })
}

/// A start's ready rule (`[start] ready`) is an idle rule of the screen
/// rules the definition ends up with.
fn check_ready(name: &str, ready: Option<&str>, screen: Option<&Screen>) -> Result<(), String> {
    let Some(ready) = ready else {
        return Ok(());
    };
    let rule = screen
        .and_then(|screen| screen.rules.rules().iter().find(|rule| rule.id == ready))
        .ok_or_else(|| {
            format!("{name}: start.ready names screen rule {ready:?}, which [screen] does not have")
        })?;
    if rule.state != Some(hide_screen_rules::State::Idle) {
        return Err(format!(
            "{name}: start.ready names screen rule {ready:?}, which is not an idle rule"
        ));
    }
    Ok(())
}

/// A file with a built-in agent's id may only replace its screen rules.
fn screen_override(name: &str, (file, screen): (Fields, Option<Rules>)) -> Result<Screen, String> {
    let other = [
        ("name", file.name.is_some()),
        ("based_on", file.based_on.is_some()),
        ("executables", file.executables.is_some()),
        ("packages", file.packages.is_some()),
        ("aliases", file.aliases.is_some()),
        ("home", file.home.is_some()),
        ("hooks", file.hooks.is_some()),
        ("account", file.account.is_some()),
        (
            "start",
            file.start_args.is_some() || file.start_ready.is_some(),
        ),
        (
            "resume",
            file.resume_session.is_some() || file.resume_last.is_some(),
        ),
    ];
    if let Some((field, _)) = other.iter().find(|(_, set)| *set) {
        return Err(format!(
            "{name}: {} is a built-in agent; its file may change [screen] only, not {field}",
            file.id
        ));
    }
    let rules = screen.ok_or_else(|| {
        format!(
            "{name}: {} is a built-in agent; its file changes [screen], which is missing",
            file.id
        )
    })?;
    Ok(Screen {
        rules: Arc::new(rules),
        source: Source::User(name.to_owned()),
    })
}

/// The names and programs already taken: one program is read as one agent
/// only, and one name (`--kind`) means one agent.
#[derive(Default)]
struct Claims {
    names: BTreeMap<String, String>,
    executables: BTreeMap<String, String>,
    packages: BTreeMap<String, String>,
}

impl Claims {
    fn claim(&mut self, file: &str, definition: &Definition) -> Result<(), String> {
        let names = std::iter::once(&definition.id).chain(&definition.aliases);
        if let Some((name, owner)) = names
            .clone()
            .find_map(|name| self.names.get(name).map(|owner| (name, owner)))
            .filter(|(_, owner)| **owner != definition.id)
        {
            return Err(format!("{file}: name {name} is taken by {owner}"));
        }
        if let Some((executable, owner)) = definition.executables.iter().find_map(|executable| {
            self.executables
                .get(executable)
                .map(|owner| (executable, owner))
        }) {
            return Err(format!("{file}: program {executable} is taken by {owner}"));
        }
        if let Some((package, owner)) = definition
            .packages
            .iter()
            .find_map(|package| self.packages.get(package).map(|owner| (package, owner)))
        {
            return Err(format!("{file}: package {package} is taken by {owner}"));
        }
        for name in names {
            self.names.insert(name.clone(), definition.id.clone());
        }
        for executable in &definition.executables {
            self.executables
                .insert(executable.clone(), definition.id.clone());
        }
        for package in &definition.packages {
            self.packages.insert(package.clone(), definition.id.clone());
        }
        Ok(())
    }
}

fn first_line(text: &str) -> &str {
    text.lines().next().unwrap_or_default()
}
