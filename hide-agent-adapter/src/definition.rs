//! Agent definition files (PRD engine-bundle-3-core-owns D-16, D-17, D-20):
//! one TOML file per agent naming how it is recognized, started and resumed,
//! which of Hide's hook dialects reads it, and the rules its state is read
//! from on the screen.
//!
//! The built-in files are `agents/*.toml` in this crate: the seven agents
//! with Hide's own features, whose identity `AgentAdapter` reads from the
//! constants `build.rs` generates out of these files, and sixteen agents
//! Herdr has screen rules for, which have the definition only. The
//! operator's own files (`~/.hide/agents/*.toml`, read by
//! `hide_kit::agent_definitions`) come after them in name order: a file with
//! a built-in agent's id replaces that agent's screen rules only, and a new
//! id either names its program and `hooks = "none"` or copies a built-in
//! agent with `based_on`. A file that cannot be used is left out alone, with
//! one line saying why.
//!
//! Built-in and user files go through the same reading and the same checks
//! ([`read_file`], [`Claims`]); only what each may say differs. Nothing here
//! reads a file system or the network: screen rules come from the app's own
//! files and the operator's, never from a download (D-19).

use std::collections::BTreeMap;
use std::sync::{Arc, LazyLock};

pub use hide_screen_rules::Rules;

mod file;
pub use file::{Hooks, SCHEMA};

/// A built-in definition's fields as constants, generated by `build.rs`
/// from `agents/<id>.toml`; `AgentAdapter` reads its identity from these.
#[derive(Debug)]
pub struct Builtin {
    pub id: &'static str,
    pub name: &'static str,
    pub executables: &'static [&'static str],
    pub aliases: &'static [&'static str],
    /// The agent's own folder under the account's home, as its parts.
    pub home: Option<&'static [&'static str]>,
    pub hooks: Hooks,
    pub start_args: &'static [&'static str],
    pub resume_session: Option<&'static [&'static str]>,
    pub resume_last: Option<&'static [&'static str]>,
    /// The file itself, for the screen rules.
    pub text: &'static str,
}

pub(crate) mod builtin {
    use super::{Builtin, Hooks};
    include!(concat!(env!("OUT_DIR"), "/builtin.rs"));
}

/// The most files read from the operator's folder; the rest are left out.
pub const MAX_USER_FILES: usize = 64;
/// The largest file read from the operator's folder.
pub const MAX_FILE_BYTES: u64 = 256 * 1024;
/// The most words a start or a resume adds after the program's name, and
/// their total size: Herdr's resume command limits, less the program.
const MAX_WORDS: usize = 63;
const MAX_WORD_BYTES: usize = 8 * 1024;
const SESSION: &str = "{session}";

/// Where a definition, or its screen rules, came from.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Source {
    Builtin,
    /// A file in the operator's folder, by its name there.
    User(String),
}

#[derive(Clone, Debug)]
pub struct Screen {
    pub rules: Arc<Rules>,
    pub source: Source,
}

/// One agent as Hide knows it.
#[derive(Clone, Debug)]
pub struct Definition {
    pub id: String,
    pub name: String,
    pub executables: Vec<String>,
    pub aliases: Vec<String>,
    /// The agent's own folder under the account's home, as its parts.
    pub home: Option<Vec<String>>,
    pub hooks: Hooks,
    pub start_args: Vec<String>,
    pub resume_session: Option<Vec<String>>,
    pub resume_last: Option<Vec<String>>,
    pub screen: Option<Screen>,
    pub source: Source,
    /// The built-in agent a user file copied.
    pub based_on: Option<String>,
}

/// A file of the operator's that was left out, and why, in one line that
/// starts with the file's name.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Rejected {
    pub file: String,
    pub reason: String,
}

/// A file found in the operator's folder, as the folder reader hands it in.
#[derive(Clone, Debug)]
pub enum UserFile {
    Text {
        name: String,
        text: String,
    },
    /// Larger than [`MAX_FILE_BYTES`]; not read.
    TooLarge {
        name: String,
        bytes: u64,
    },
    /// Past the first [`MAX_USER_FILES`] in name order; not read.
    BeyondLimit {
        name: String,
    },
    Unreadable {
        name: String,
        error: String,
    },
}

/// Every agent this Hide knows: the built-in ones, then the operator's, with
/// the operator's files that were left out.
#[derive(Clone, Debug)]
pub struct Catalog {
    pub definitions: Vec<Definition>,
    pub rejected: Vec<Rejected>,
}

/// The built-in definitions, read and checked once. A built-in file that
/// fails a check is a bug this crate's tests catch, never an operator's
/// problem, so it stops the process with the reason.
pub fn builtins() -> &'static [Definition] {
    static BUILTINS: LazyLock<Vec<Definition>> = LazyLock::new(|| {
        let mut claims = Claims::default();
        builtin::ALL
            .iter()
            .map(|builtin| {
                let name = format!("{}.toml", builtin.id);
                read_file(&name, builtin.text, Origin::Builtin)
                    .and_then(|file| new_definition(&name, file, Source::Builtin))
                    .and_then(|definition| claims.claim(&name, &definition).map(|()| definition))
                    .unwrap_or_else(|reason| panic!("built-in agent definition: {reason}"))
            })
            .collect()
    });
    &BUILTINS
}

/// The built-in definition with this id.
pub fn builtin(id: &str) -> Option<&'static Definition> {
    builtins().iter().find(|definition| definition.id == id)
}

impl Catalog {
    /// The built-in definitions with the operator's files read over them,
    /// in the order handed in (the folder's name order).
    pub fn read(files: Vec<UserFile>) -> Self {
        let mut definitions = builtins().to_vec();
        let mut claims = Claims::default();
        for definition in &definitions {
            claims
                .claim("", definition)
                .expect("built-in definitions claim distinct names");
        }
        let mut overridden: BTreeMap<String, String> = BTreeMap::new();
        let mut rejected = Vec::new();
        for file in files {
            let (name, text) = match file {
                UserFile::Text { name, text } => (name, text),
                UserFile::TooLarge { name, bytes } => {
                    let reason = format!(
                        "{name}: {bytes} bytes, more than the {MAX_FILE_BYTES} a file may hold"
                    );
                    rejected.push(Rejected { file: name, reason });
                    continue;
                }
                UserFile::BeyondLimit { name } => {
                    let reason =
                        format!("{name}: past the first {MAX_USER_FILES} files, which are read");
                    rejected.push(Rejected { file: name, reason });
                    continue;
                }
                UserFile::Unreadable { name, error } => {
                    let reason = format!("{name}: could not be read: {error}");
                    rejected.push(Rejected { file: name, reason });
                    continue;
                }
            };
            let result = read_file(&name, &text, Origin::User).and_then(|file| {
                if let Some(index) = definitions.iter().position(|definition| {
                    definition.source == Source::Builtin && definition.id == file.id
                }) {
                    let screen = screen_override(&name, file)?;
                    if let Some(earlier) =
                        overridden.insert(definitions[index].id.clone(), name.clone())
                    {
                        return Err(format!(
                            "{name}: {earlier} already replaces the screen rules of {}",
                            definitions[index].id
                        ));
                    }
                    definitions[index].screen = Some(screen);
                    return Ok(());
                }
                let definition = match file.based_on.clone() {
                    Some(base) => based_on(&name, file, &base)?,
                    None => new_definition(&name, file, Source::User(name.clone()))?,
                };
                claims.claim(&name, &definition)?;
                definitions.push(definition);
                Ok(())
            });
            if let Err(reason) = result {
                rejected.push(Rejected { file: name, reason });
            }
        }
        Self {
            definitions,
            rejected,
        }
    }
}

#[derive(Clone, Copy, Eq, PartialEq)]
enum Origin {
    Builtin,
    User,
}

/// A file read and checked on its own, before it is set beside the others.
struct Checked {
    id: String,
    name: Option<String>,
    based_on: Option<String>,
    executables: Option<Vec<String>>,
    aliases: Option<Vec<String>>,
    home: Option<Vec<String>>,
    hooks: Option<Hooks>,
    start_args: Option<Vec<String>>,
    resume_session: Option<Vec<String>>,
    resume_last: Option<Vec<String>>,
    screen: Option<Rules>,
}

/// Parse one file and check every field it carries: the one reading of a
/// definition, for built-in files and the operator's alike.
fn read_file(name: &str, text: &str, origin: Origin) -> Result<Checked, String> {
    let file: file::File = toml::from_str(text).map_err(|error| {
        let error = error.to_string();
        let line = error.lines().next().unwrap_or_default();
        format!("{name}: not a definition file: {line}")
    })?;
    if file.schema != SCHEMA {
        return Err(format!(
            "{name}: schema {} is not one this Hide reads (it reads {SCHEMA})",
            file.schema
        ));
    }
    if !valid_id(&file.id) {
        return Err(format!(
            "{name}: id {:?} is not 1 to 32 lowercase letters, digits and dashes",
            file.id
        ));
    }
    if origin == Origin::Builtin && file.based_on.is_some() {
        return Err(format!("{name}: based_on is for the operator's files"));
    }
    if let Some(display) = &file.name
        && (display.trim().is_empty()
            || display.chars().count() > 64
            || display.chars().any(char::is_control))
    {
        return Err(format!("{name}: name must be 1 to 64 printable characters"));
    }
    if let Some(executables) = &file.executables {
        check_executables(name, executables)?;
    }
    if let Some(aliases) = &file.aliases
        && let Some(alias) = aliases.iter().find(|alias| !valid_alias(alias))
    {
        return Err(format!(
            "{name}: alias {alias:?} is not 1 to 32 lowercase letters, digits, dashes and underscores"
        ));
    }
    let home = file
        .home
        .as_deref()
        .map(|home| home_parts(name, home))
        .transpose()?;
    let start_args = file.start.map(|start| start.args);
    if let Some(args) = &start_args {
        check_words(name, "start.args", args, 0)?;
    }
    let resume = file.resume.unwrap_or_default();
    if let Some(words) = &resume.session {
        check_words(name, "resume.session", words, 1)?;
    }
    if let Some(words) = &resume.last {
        check_words(name, "resume.last", words, 0)?;
    }
    let screen = file
        .screen
        .map(|table| {
            table
                .try_into::<hide_screen_rules::Manifest>()
                .map_err(|error| error.to_string())
                .and_then(hide_screen_rules::Manifest::compile)
                .map_err(|error| format!("{name}: screen rules: {}", first_line(&error)))
        })
        .transpose()?;
    Ok(Checked {
        id: file.id,
        name: file.name,
        based_on: file.based_on,
        executables: file.executables,
        aliases: file.aliases,
        home,
        hooks: file.hooks,
        start_args,
        resume_session: resume.session,
        resume_last: resume.last,
        screen,
    })
}

/// A definition of its own: a built-in file, or an operator's file for an
/// agent Hide knows only through it, which names its program and reads the
/// state from the screen alone.
fn new_definition(name: &str, file: Checked, source: Source) -> Result<Definition, String> {
    let display = file
        .name
        .ok_or_else(|| format!("{name}: name is missing"))?;
    let executables = file
        .executables
        .ok_or_else(|| format!("{name}: executables is missing"))?;
    let hooks = file
        .hooks
        .ok_or_else(|| format!("{name}: hooks is missing"))?;
    if source != Source::Builtin && hooks != Hooks::None {
        return Err(format!(
            "{name}: hooks must be \"none\"; a file takes another agent's hooks with based_on"
        ));
    }
    Ok(Definition {
        id: file.id,
        name: display,
        executables,
        aliases: file.aliases.unwrap_or_default(),
        home: file.home,
        hooks,
        start_args: file.start_args.unwrap_or_default(),
        resume_session: file.resume_session,
        resume_last: file.resume_last,
        screen: file.screen.map(|rules| Screen {
            rules: Arc::new(rules),
            source: source.clone(),
        }),
        source,
        based_on: None,
    })
}

/// A copy of a built-in agent with what the file says in place of its
/// fields: the copy keeps the agent's hooks and everything Hide does with
/// them, and a copy of a copy is refused.
fn based_on(name: &str, file: Checked, base: &str) -> Result<Definition, String> {
    let Some(builtin) = builtin(base) else {
        return Err(format!("{name}: based_on {base} is not a built-in agent"));
    };
    if file.hooks.is_some() {
        return Err(format!(
            "{name}: hooks comes from based_on {base} and cannot be set"
        ));
    }
    let display = file
        .name
        .ok_or_else(|| format!("{name}: name is missing"))?;
    let source = Source::User(name.to_owned());
    Ok(Definition {
        id: file.id,
        name: display,
        executables: file
            .executables
            .unwrap_or_else(|| builtin.executables.clone()),
        aliases: file.aliases.unwrap_or_default(),
        home: file.home.or_else(|| builtin.home.clone()),
        hooks: builtin.hooks,
        start_args: file
            .start_args
            .unwrap_or_else(|| builtin.start_args.clone()),
        resume_session: file
            .resume_session
            .or_else(|| builtin.resume_session.clone()),
        resume_last: file.resume_last.or_else(|| builtin.resume_last.clone()),
        screen: match file.screen {
            Some(rules) => Some(Screen {
                rules: Arc::new(rules),
                source: source.clone(),
            }),
            None => builtin.screen.clone(),
        },
        source,
        based_on: Some(base.to_owned()),
    })
}

/// A file with a built-in agent's id may only replace its screen rules.
fn screen_override(name: &str, file: Checked) -> Result<Screen, String> {
    let other = [
        ("name", file.name.is_some()),
        ("based_on", file.based_on.is_some()),
        ("executables", file.executables.is_some()),
        ("aliases", file.aliases.is_some()),
        ("home", file.home.is_some()),
        ("hooks", file.hooks.is_some()),
        ("start", file.start_args.is_some()),
        (
            "resume",
            file.resume_session.is_some() || file.resume_last.is_some(),
        ),
    ];
    if let Some((field, _)) = other.iter().find(|(_, set)| *set) {
        return Err(format!(
            "{name}: {} is a built-in agent; its file may change [screen] only, not {field}",
            file.id
        ));
    }
    let rules = file.screen.ok_or_else(|| {
        format!(
            "{name}: {} is a built-in agent; its file changes [screen], which is missing",
            file.id
        )
    })?;
    Ok(Screen {
        rules: Arc::new(rules),
        source: Source::User(name.to_owned()),
    })
}

/// The names and programs already taken: one program is read as one agent
/// only, and one name (`--kind`) means one agent.
#[derive(Default)]
struct Claims {
    names: BTreeMap<String, String>,
    executables: BTreeMap<String, String>,
}

impl Claims {
    fn claim(&mut self, file: &str, definition: &Definition) -> Result<(), String> {
        let names = std::iter::once(&definition.id).chain(&definition.aliases);
        if let Some((name, owner)) = names
            .clone()
            .find_map(|name| self.names.get(name).map(|owner| (name, owner)))
            .filter(|(_, owner)| **owner != definition.id)
        {
            return Err(format!("{file}: name {name} is taken by {owner}"));
        }
        if let Some((executable, owner)) = definition.executables.iter().find_map(|executable| {
            self.executables
                .get(executable)
                .map(|owner| (executable, owner))
        }) {
            return Err(format!("{file}: program {executable} is taken by {owner}"));
        }
        for name in names {
            self.names.insert(name.clone(), definition.id.clone());
        }
        for executable in &definition.executables {
            self.executables
                .insert(executable.clone(), definition.id.clone());
        }
        Ok(())
    }
}

fn valid_id(id: &str) -> bool {
    (1..=32).contains(&id.len())
        && id
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
        && !id.starts_with('-')
}

fn valid_alias(alias: &str) -> bool {
    (1..=32).contains(&alias.len())
        && alias.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-' || byte == b'_'
        })
}

/// Programs are compared by their file's name, so none is a path; the first
/// is what a start types into the pane's shell, so it is a plain command
/// name, as Herdr's resume check holds it (`validate_resume_argv`).
fn check_executables(name: &str, executables: &[String]) -> Result<(), String> {
    let Some(first) = executables.first() else {
        return Err(format!("{name}: executables is empty"));
    };
    if let Some(bad) = executables.iter().find(|executable| {
        executable.is_empty()
            || executable.len() > 64
            || executable.contains(['/', '\\'])
            || executable.chars().any(char::is_control)
    }) {
        return Err(format!("{name}: program {bad:?} is not a file name"));
    }
    let plain = !first.starts_with('-')
        && first
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-' | b'.'));
    if !plain {
        return Err(format!(
            "{name}: the first program {first:?} is started by name and must be a plain command name"
        ));
    }
    Ok(())
}

/// Words a start or a resume types after the program: Herdr's resume
/// command rules (no control character, no apostrophe, 64 words and 8 KiB
/// with the program), and `{session}` exactly where the field takes it.
fn check_words(name: &str, field: &str, words: &[String], sessions: usize) -> Result<(), String> {
    if words.len() > MAX_WORDS || words.iter().map(String::len).sum::<usize>() > MAX_WORD_BYTES {
        return Err(format!(
            "{name}: {field} holds more than {MAX_WORDS} words or {MAX_WORD_BYTES} bytes"
        ));
    }
    if words
        .iter()
        .any(|word| word.contains('\'') || word.chars().any(char::is_control))
    {
        return Err(format!(
            "{name}: {field} holds an apostrophe or a control character"
        ));
    }
    let found = words
        .iter()
        .map(|word| word.matches(SESSION).count())
        .sum::<usize>();
    if found != sessions {
        return Err(if sessions == 0 {
            format!("{name}: {field} cannot name {SESSION}")
        } else {
            format!("{name}: {field} names {SESSION} {found} times, not once")
        });
    }
    Ok(())
}

fn home_parts(name: &str, home: &str) -> Result<Vec<String>, String> {
    let parts: Option<Vec<String>> = home
        .strip_prefix("~/")
        .map(|rest| rest.split('/').map(str::to_owned).collect());
    match parts {
        Some(parts)
            if parts.iter().all(|part| {
                !part.is_empty() && part != "." && part != ".." && !part.contains('\\')
            }) =>
        {
            Ok(parts)
        }
        _ => Err(format!(
            "{name}: home {home:?} is not a folder under the home folder, written ~/<folder>"
        )),
    }
}

fn first_line(text: &str) -> &str {
    text.lines().next().unwrap_or_default()
}
