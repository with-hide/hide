#!/usr/bin/env node
// The Keyboard shortcuts page is generated from `web/src/shortcuts.ts`, the one registry that also draws the
// app menu, the shortcut sheet and Settings, Shortcuts: the registry is imported as it stands (no build, no copy),
// each system's keys come from its own `systemRegistry` and `displayChord`, and nothing about a command or a key
// is typed here. `problems` holds a page to the registry: every command is a row, with its keys on every system.
// Usage: shortcuts-reference.mjs > shortcuts.md
import { register } from "node:module";
import { pathToFileURL } from "node:url";

if (!process.features.typescript) {
  throw new Error("shortcuts-reference: this node cannot read TypeScript; use node 22.18 or later (CI) or node 24");
}
register("./ts-extensionless.mjs", import.meta.url);
const registryUrl = new URL("../../web/src/shortcuts.ts", import.meta.url).href;

/** The registry module: the commands, each system's keys and how a chord is written. */
export const load = () => import(registryUrl);

/** The systems the page has a column for, in order. Windows and Linux press the same keys (`KeySystem` "pc"). */
export const SYSTEMS = [
  { name: "macOS", system: "mac" },
  { name: "Windows", system: "pc" },
  { name: "Linux", system: "pc" },
];

const escapeCell = (text) => text.replace(/\|/g, "\\|");
/** A chord as an inline code span; a chord holding a backtick (`⌥``) is fenced by two. */
const code = (text) => (text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``);
const cell = (chord) => (chord ? escapeCell(code(chord)) : "none");

/** The rows of one group on one host, per system: `Map<command id, { title, chords: [string|null per SYSTEMS entry] }>`. */
function rowsOf(reg, host, group, registryOf) {
  const rows = new Map();
  SYSTEMS.forEach(({ system }, index) => {
    for (const row of reg.sheetRows(group, registryOf(system), host, system)) {
      const entry = rows.get(row.id) ?? { id: row.id, title: row.title, chords: [] };
      entry.chords[index] = row.chord;
      rows.set(row.id, entry);
    }
  });
  return [...rows.values()];
}

const groupsOf = (registry) => [...new Set(registry.map((command) => command.group))];

function note(reg, command, editable) {
  const parts = [];
  // A passthrough command is answered by the Explorer's tree while it holds the keyboard; a terminal keeps the keys otherwise.
  if (command.passthrough || reg.systemRegistry("pc").find((row) => row.id === command.id)?.passthrough) parts.push("Only while the Explorer holds the keyboard");
  parts.push(editable.has(command.id) ? "Change in Settings" : "Fixed");
  return parts.join(". ");
}

/** The page's Markdown, front matter included, from the registry module `reg` (the real one unless a test passes another). */
export function render(reg) {
  const registry = reg.REGISTRY;
  const editable = new Set(reg.EDITABLE_PANE_COMMANDS);
  const byId = new Map(registry.map((command) => [command.id, command]));
  const registryOf = (system) => reg.systemRegistry(system);
  const chordOf = (id, system, host = "electron") => reg.displayCommand(id, host, registryOf(system), system);
  const lines = [];
  const out = (...text) => lines.push(...text);

  out("---", "title: Keyboard shortcuts", "description: Every shortcut of the Hide app on macOS, Windows and Linux.", "sidebar:", "  order: 2", "---", "", "<!-- Generated by scripts/docs/shortcuts-reference.mjs from web/src/shortcuts.ts; do not edit by hand. -->", "", "<style>.sl-markdown-content table code { white-space: nowrap; }</style>", "");
  // A chord stays whole on a phone: the table scrolls sideways instead of breaking `Ctrl+Shift+T` mid-word.
  out("This page lists every shortcut of the Hide desktop app, in the order of the app's own shortcut sheet.");
  out(`It is generated from the app's shortcut table, so it always matches the version it was built from.`, "");
  out("## Find and change shortcuts", "");
  out(`- Open the list in the app with ${code(chordOf("shortcuts", "mac"))} on macOS or ${code(chordOf("shortcuts", "pc"))} on Windows and Linux. The same sheet opens from the Help menu, under \`Keyboard shortcuts\`.`);
  out(`- Change one in Settings, \`Shortcuts\`: press the chip beside a command, press the new keys, and it applies at once. \`Escape\` cancels. The row's \`Restore default\` and \`Clear\` controls appear when you point at the row, and \`Restore all defaults\` resets every command.`);
  out(`- A command marked \`none\` has no shortcut until you give it one. Only the commands marked \`Change in Settings\` can be changed; the others are fixed.`, "");
  out("## How Windows and Linux differ from macOS", "");
  out("Windows and Linux press the same keys, so both have a column.");
  out("Where macOS uses `⌘`, Windows and Linux use `Ctrl+Shift`, as Windows Terminal and GNOME Terminal do. That keeps plain `Ctrl` keys such as `Ctrl+C` and `Ctrl+R` for your shell and your agents.");
  out("Where a macOS shortcut adds `⇧` or `⌥` to `⌘`, Windows and Linux use `Alt+Shift`. A few shortcuts keep the key people already know there (text size, the tab beside, Move to Trash); they are in the table.", "");

  for (const group of groupsOf(registry)) {
    out(`## ${group}`, "", "| Command | macOS | Windows | Linux | Note |", "| --- | --- | --- | --- | --- |");
    for (const row of rowsOf(reg, "electron", group, registryOf)) {
      const command = byId.get(row.id);
      const numbered = reg.numberedCommand(row.id);
      const noteText = numbered ? "Fixed" : note(reg, command, editable);
      out(`| ${escapeCell(row.title)} | ${row.chords.map(cell).join(" | ")} | ${noteText} |`);
    }
    out("");
  }

  const holds = ["tabs", "agents", "devices"].map((family) => {
    const label = (system) => reg.modifierLabel(reg.familyModifiers(family, registryOf(system), "electron"), system);
    return { family, mac: label("mac"), pc: label("pc") };
  });
  out("## Numbers on screen", "");
  out("Hold the first keys of a numbered shortcut and the app floats the numbers over the tabs, the agents or the devices.", "");
  out("| Hold | macOS | Windows and Linux |", "| --- | --- | --- |");
  const names = { tabs: "Tab numbers", agents: "Agent numbers", devices: "Device numbers" };
  for (const hold of holds) out(`| ${names[hold.family]} | ${code(hold.mac)} | ${code(hold.pc)} |`);
  out("");

  out("## In a terminal", "");
  out("A terminal pane sends keys to the program in it, so copy and paste use the terminal's own keys:", "");
  out("| Action | macOS | Windows | Linux |", "| --- | --- | --- | --- |");
  const terminal = (chord) => SYSTEMS.map(({ system }) => code(reg.displayChord(reg.modChord(chord, system), system)));
  out(`| Copy the selection | ${terminal(reg.TERMINAL_COPY).join(" | ")} |`);
  out(`| Paste | ${terminal(reg.TERMINAL_PASTE).join(" | ")} |`, "");
  out("On Windows and Linux, `Ctrl+C` also copies while text is selected; with nothing selected it reaches the program as an interrupt.", "");

  out("## In a browser tab", "");
  out("When you open Hide in a browser tab instead of the desktop app, the browser keeps some shortcuts for itself, so these commands use other keys or have none.");
  out("The commands not listed here are the same as in the app.", "");
  out("| Command | macOS | Windows | Linux |", "| --- | --- | --- | --- |");
  for (const group of groupsOf(registry)) {
    const app = new Map(rowsOf(reg, "electron", group, registryOf).map((row) => [row.id, row]));
    for (const row of rowsOf(reg, "browser", group, registryOf)) {
      const same = row.chords.every((chord, index) => chord === app.get(row.id).chords[index]);
      if (!same) out(`| ${escapeCell(row.title)} | ${row.chords.map(cell).join(" | ")} |`);
    }
  }
  out("");
  return lines.join("\n");
}

/** Whether a table row names `chord` as a whole cell word (inside a code span or beside a folded range), not as a prefix of another chord. */
const holds = (row, chord) => new RegExp(`[\`\\s]${chord.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\`\\s]`).test(row);
const rowsOfPage = (page) => page.split("\n").filter((line) => line.startsWith("| "));

/**
 * What a generated page lacks of the registry `reg`: the commands with no row in the app's tables and the commands whose
 * keys on a system are not in their row. Read from the registry itself, never from how `render` walks it, so a group the
 * generator skips, a folded family it drops or a system it forgets is a problem here.
 */
export function problems(reg, page) {
  const found = [];
  const rows = rowsOfPage(page);
  const rowOf = (title) => rows.find((row) => row.startsWith(`| ${escapeCell(title)} |`));
  for (const system of ["mac", "pc"]) {
    for (const command of reg.systemRegistry(system)) {
      const numbered = reg.numberedCommand(command.id);
      const title = numbered ? `${reg.NUMBERED_FAMILIES.find((family) => family.family === numbered.family).title} 1-9` : command.title;
      const row = rowOf(title);
      if (!row) {
        found.push(`command ${command.id} (${title}) has no row`);
        continue;
      }
      if (numbered && numbered.number !== 1 && numbered.number !== 9) continue;
      const chord = reg.hostChord(command, "electron");
      if (chord && !holds(row, reg.displayChord(chord, system))) found.push(`command ${command.id} is missing ${reg.displayChord(chord, system)} for ${system === "mac" ? "macOS" : "Windows and Linux"}`);
      if (!chord && !row.includes("none")) found.push(`command ${command.id} has no chord on ${system} and its row does not say none`);
    }
  }
  return [...new Set(found)];
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const reg = await load();
  const page = render(reg);
  const missing = problems(reg, page);
  if (missing.length) {
    console.error(`shortcuts-reference: the page does not hold the registry:\n${missing.map((line) => `  ${line}`).join("\n")}`);
    process.exit(1);
  }
  process.stdout.write(`${page}\n`);
}
